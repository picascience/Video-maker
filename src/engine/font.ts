// accent : pixels [dx, dy] au-dessus de la lettre de base
const ACUTE: [number, number][] = [[3, -3], [2, -2]];
const GRAVE: [number, number][] = [[1, -3], [2, -2]];
const CIRC: [number, number][] = [[2, -3], [1, -2], [3, -2]];
const TREMA: [number, number][] = [[1, -2], [3, -2]];
const ACCENTS: Record<string, [string, [number, number][]]> = {
  É: ['E', ACUTE], È: ['E', GRAVE], Ê: ['E', CIRC], Ë: ['E', TREMA],
  À: ['A', GRAVE], Â: ['A', CIRC], Ù: ['U', GRAVE], Û: ['U', CIRC],
  Ô: ['O', CIRC], Î: ['I', CIRC], Ï: ['I', TREMA], Ç: ['C', []],
};

export const GLYPH_W = 5;
export const GLYPH_H = 7;
const ADVANCE = 6;

export const measureText = (text: string, size = 1) => Math.max(0, text.length * ADVANCE - 1) * size;

const plot = (f: Frame, x: number, y: number, size: number, c: RGB) => f.rect(x, y, size, size, c);

const drawRaw = (f: Frame, text: string, x: number, y: number, size: number, c: RGB) => {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const acc = ACCENTS[ch];
    const rows = G[acc ? acc[0] : ch] ?? G['?'];
    for (let r = 0; r < GLYPH_H; r++)
      for (let col = 0; col < GLYPH_W; col++)
        if (rows[r][col] === '#') plot(f, cx + col * size, y + r * size, size, c);
    if (acc) for (const [dx, dy] of acc[1]) plot(f, cx + dx * size, y + dy * size, size, c);
    cx += ADVANCE * size;
  }
};

export interface TextStyle {
  size?: number;
  color: RGB;
  /** Contour 1 px : indispensable pour rester lisible sur un fond détaillé. */
  outline?: RGB;
  /** Ombre portée décalée vers le bas-droite. */
  shadow?: RGB;
}

export const drawText = (f: Frame, text: string, x: number, y: number, style: TextStyle) => {
  const size = style.size ?? 1;
  if (style.shadow) {
    for (const [ox, oy] of [[1, 2], [2, 2], [0, 2], [2, 1]]) drawRaw(f, text, x + ox, y + oy, size, style.shadow);
  }
  if (style.outline) {
    for (let oy = -1; oy <= 1; oy++)
      for (let ox = -1; ox <= 1; ox++) if (ox || oy) drawRaw(f, text, x + ox, y + oy, size, style.outline);
  }
  drawRaw(f, text, x, y, size, style.color);
};

/** Texte centré horizontalement sur cx. */
export const drawTextCentered = (f: Frame, text: string, cx: number, y: number, style: TextStyle) => {
  drawText(f, text, Math.round(cx - measureText(text, style.size ?? 1) / 2), y, style);
};
